_FALSE_POS = re.compile(r"사고력|사고방식|사고 방식|사고싶|사고 싶|사고팔|사고 팔|사고\s*나면")


def find_matches(text: str, words: Iterable[str]) -> List[str]:
    hits = []
    t = _FALSE_POS.sub(" ", text or "")
    for w in words:
        if w and w in t:
            hits.append(w)
    return hits


# 부정 키워드가 들어 있지만 실제로는 부정적이지 않은 표현 ('폭발적 인기', '사고방식' 등)
_BENIGN = ("폭발적", "사고방식", "사고력", "사고 싶", "사고팔", "사고 파", "기소유예")


def flag_text(text: str, fcfg: Dict[str, Any]) -> Dict[str, List[str]]:
    clean_text = text
    for b in _BENIGN:
        clean_text = clean_text.replace(b, " ")
    return {
        "hard": find_matches(clean_text, fcfg.get("negative_hard", [])),
        "soft": find_matches(text, fcfg.get("negative_soft", [])),
        "politics": find_matches(text, fcfg.get("politics", [])),
    }


def classify_text(text: str) -> str:
    """키워드 점수로 분류. 동점/무점이면 '미분류'."""
    scores: Counter = Counter()
    for cat, words in CATEGORY_KEYWORDS.items():
        for w in words:
            if w in text:
                scores[cat] += 1
    if not scores:
        return "미분류"
    return scores.most_common(1)[0][0]


def resolve_category(votes: List[str], text: str) -> str:
    """원 채널이 붙여준 카테고리 투표를 우선, 없으면 키워드 분류."""
    votes = [v for v in votes if v]
    if votes:
        c = Counter(votes).most_common()
        top, n = c[0]
        return top
    return classify_text(text)
